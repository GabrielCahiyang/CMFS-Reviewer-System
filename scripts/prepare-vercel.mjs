import { lstat, mkdir, readFile, readdir, rmdir, unlink, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

// Retire the old custom-extension entry points without touching their sources.
const legacyEntries = [
  ['src/app/(frontend)/layout.vercel.tsx', "export { default, metadata } from './layout'\n"],
  ['src/app/(frontend)/page.vercel.tsx', "export { default } from './page'\n"],
  ['src/app/(frontend)/not-found.vercel.tsx', "export { default } from './not-found'\n"],
  ['src/app/(frontend)/error.vercel.tsx', "'use client'\nexport { default } from './error'\n"],
  ['src/app/(frontend)/[...slug]/page.vercel.tsx', "export { default, generateStaticParams } from './page'\nexport const dynamicParams = false\n"],
  ...['sessions', 'events', 'admin', 'account'].map(name => [
    `src/app/api/study/${name}/route.vercel.ts`,
    `export { ${['sessions', 'events'].includes(name) ? 'POST' : 'GET'} } from './route'\nexport const runtime = 'nodejs'\nexport const dynamic = 'force-dynamic'\n`,
  ]),
]

const defaultRoot = fileURLToPath(new URL('../', import.meta.url))
const marker = '.cfms-vercel-generated'
const owner = 'CFMS Vercel generated entry points v1\n'
const heading = '// Generated by scripts/prepare-vercel.mjs. Do not edit.\n'
const entries = [
  ['layout.tsx', "export { default, metadata } from '../src/app/(frontend)/layout'\n"],
  ['page.tsx', "export { default } from '../src/app/(frontend)/page'\n"],
  ['not-found.tsx', "export { default } from '../src/app/(frontend)/not-found'\n"],
  ['error.tsx', "'use client'\nexport { default } from '../src/app/(frontend)/error'\n"],
  ['[...slug]/page.tsx', "export { default, generateStaticParams } from '../../src/app/(frontend)/[...slug]/page'\nexport const dynamicParams = false\n"],
  ...['sessions', 'events', 'admin', 'account'].map(name => [
    `api/study/${name}/route.ts`,
    `export { ${['sessions', 'events'].includes(name) ? 'POST' : 'GET'} } from '../../../../src/app/api/study/${name}/route'\nexport const runtime = 'nodejs'\nexport const dynamic = 'force-dynamic'\n`,
  ]),
]

async function optionalText(file) {
  try { return await readFile(file, 'utf8') }
  catch (error) { if (error.code === 'ENOENT') return undefined; throw error }
}

async function ownedApp(root) {
  const app = path.resolve(root, 'app')
  let stat
  try { stat = await lstat(app) }
  catch (error) { if (error.code === 'ENOENT') return undefined; throw error }
  if (!stat.isDirectory() || stat.isSymbolicLink() || await optionalText(path.join(app, marker)) !== owner)
    throw new Error('The root app directory is not CFMS-generated. Refusing to change it.')
  const files = [], directories = []
  async function walk(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const full = path.join(directory, entry.name)
      if (entry.isSymbolicLink()) throw new Error('Unexpected link in generated app directory.')
      if (entry.isDirectory()) { directories.push(full); await walk(full) }
      else files.push(full)
    }
  }
  await walk(app)
  const expected = new Map([[marker, owner], ...entries.map(([name, content]) => [name, heading + content])]
    .map(([name, content]) => [path.resolve(app, name), content]))
  if (files.some(file => !expected.has(file)))
    throw new Error('Unexpected files in generated app directory. Refusing to change it.')
  for (const file of files.filter(file => file !== path.join(app, marker))) {
    if ((await readFile(file, 'utf8')).replaceAll('\r\n', '\n') !== expected.get(file))
      throw new Error('A generated entry point was edited. Refusing to change it.')
  }
  return { app, files, directories }
}

export async function prepareVercel(root = defaultRoot) {
  const existing = await ownedApp(root)
  const app = path.resolve(root, 'app')
  if (!existing) {
    await mkdir(app)
    await writeFile(path.join(app, marker), owner, { flag: 'wx' })
  }
  for (const [name, content] of entries) {
    const target = path.resolve(app, name)
    await mkdir(path.dirname(target), { recursive: true })
    if (await optionalText(target) !== heading + content) await writeFile(target, heading + content)
  }
  for (const [name, content] of legacyEntries) {
    const target = path.resolve(root, name)
    const previous = await optionalText(target)
    if (previous === undefined) continue
    if (previous.replaceAll('\r\n', '\n') !== content) throw new Error('Edited legacy Vercel entry point was preserved: ' + name)
    await unlink(target)
  }
  return entries.map(([name]) => 'app/' + name)
}

export async function clearVercel(root = defaultRoot) {
  const existing = await ownedApp(root)
  if (!existing) return
  // Only exact allowlisted generated files are removed. Source in src/app is untouched.
  for (const file of existing.files.filter(file => file !== path.join(existing.app, marker))) await unlink(file)
  for (const directory of existing.directories.sort((a, b) => b.length - a.length)) await rmdir(directory)
  await unlink(path.join(existing.app, marker))
  await rmdir(existing.app)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  prepareVercel().then(files => {
    console.log(`Prepared ${files.length} Vercel entry points; Make/Payload source preserved.`)
  }).catch(error => { console.error(error.message); process.exitCode = 1 })
}
